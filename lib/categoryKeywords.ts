function tokenize(name: string): string[] {
  return name
    .toLowerCase()
    .replace(/[^\p{L}\p{N}'\s]/gu, ' ')
    .split(/\s+/)
    .filter(Boolean);
}

function matches(keyword: string, normalized: string, tokens: string[]): boolean {
  const k = keyword.toLowerCase();
  if (k.startsWith('=')) return tokens.includes(k.slice(1));
  if (k.includes(' ')) return normalized.includes(k);
  if (k.length <= 2) return tokens.includes(k);
  return tokens.some((tok) => tok.startsWith(k));
}

export function guessCategoryByKeywords(name: string): string | null {
  const normalized = name.trim().toLowerCase().replace(/\s+/g, ' ');
  if (!normalized) return null;
  const tokens = tokenize(normalized);
  // Phrases first ("פלפל שחור", "מרק עוף"), so a specific phrase beats a
  // single word from an earlier rule; then single-word prefixes in rule order.
  for (const phrasePass of [true, false]) {
    for (const [category, keywords] of RULES) {
      for (const k of keywords) {
        if (k.includes(' ') !== phrasePass) continue;
        if (matches(k, normalized, tokens)) return category;
      }
    }
  }
  return null;
}
